function buildIndex(): OracleIndex {
  const index: OracleIndex = {
    publicWorkerByPersonNumber: new Map(),
    workerByPersonId: new Map(),
    assignmentByPersonId: new Map(),
    absencesByPersonId: new Map(),
    contactsByContactPersonId: new Map(),
    relationshipsByPersonId: new Map()
  };

  if (existsSync(ORACLE_SEED_DATA_PATH)) {
    const seed = JSON.parse(readFileSync(ORACLE_SEED_DATA_PATH, "utf8")) as OracleSeedFile;
    const collections = seed.oracle_fusion_hcm_api.collections;

    for (const worker of collections.publicWorkers.items) {
      index.publicWorkerByPersonNumber.set(worker.PersonNumber, worker);
    }
    for (const worker of collections.workers.items) {
      index.workerByPersonId.set(worker.PersonId, worker);
    }
    for (const assignment of collections.assignments.items) {
      if (assignment.PrimaryAssignmentFlag) {
        index.assignmentByPersonId.set(assignment.PersonId, assignment);
      }
    }
    for (const absence of collections.absences.items) {
      const existing = index.absencesByPersonId.get(absence.PersonId) ?? [];
      existing.push(absence);
      index.absencesByPersonId.set(absence.PersonId, existing);
    }
    for (const contact of collections.hcmContacts.items) {
      index.contactsByContactPersonId.set(contact.ContactPersonId, contact);
    }
    for (const relationship of collections.contactRelationships.items) {
      const existing = index.relationshipsByPersonId.get(relationship.PersonId) ?? [];
      existing.push(relationship);
      index.relationshipsByPersonId.set(relationship.PersonId, existing);
    }
  }

  addLegacyDemoWorkers(index);
  return index;
}

function getIndex(): OracleIndex {
  if (!cachedIndex) {
    cachedIndex = buildIndex();
  }
  return cachedIndex;
}

