/**
 * Canonical mapping from Oracle's `AssignmentStatusType` (plus any active
 * approved absence) to IST's `dutyStatus` enum - see the "Canonical Mapping"
 * table in docs/oracle-fusion-hcm-integration.md.
 */
function dutyStatusFromOracle(assignmentStatusType: string, hasApprovedAbsence: boolean): StaffProfile["dutyStatus"] {
  if (assignmentStatusType === "INACTIVE") {
    return "inactive";
  }
  if (assignmentStatusType === "LEAVE_OF_ABSENCE" || hasApprovedAbsence) {
    return "on-leave";
  }
  return "active";
}

function relationshipTypeFromOracle(relationshipType: string): DependentProfile["relationshipType"] {
  if (relationshipType === "SPOUSE") return "spouse";
  if (relationshipType === "SON" || relationshipType === "DAUGHTER") return "child";
  if (relationshipType === "PARENT") return "parent";
  return "other";
}

function biologicalSexFromOracleGender(gender: string): "male" | "female" {
  return gender === "F" ? "female" : "male";
}

export function ageFromDateOfBirth(dateOfBirthIso: string): number {
  const dob = new Date(dateOfBirthIso);
  if (Number.isNaN(dob.getTime())) {
    return 0;
  }
  const now = new Date();
  let age = now.getUTCFullYear() - dob.getUTCFullYear();
  if (now.getUTCMonth() < dob.getUTCMonth() || (now.getUTCMonth() === dob.getUTCMonth() && now.getUTCDate() < dob.getUTCDate())) {
    age -= 1;
  }
  return Math.max(age, 0);
}

function dependentsForPerson(index: OracleIndex, personId: number): DependentProfile[] {
  const relationships = index.relationshipsByPersonId.get(personId) ?? [];
  const dependents: DependentProfile[] = [];
  for (const relationship of relationships) {
    const contact = index.contactsByContactPersonId.get(relationship.ContactPersonId);
    if (!contact) {
      continue;
    }
    dependents.push({
      id: relationship.legacyDependentId ?? `dep_${relationship.ContactRelationshipId.toLowerCase()}`,
      relationshipType: relationshipTypeFromOracle(relationship.RelationshipType),
      age: ageFromDateOfBirth(contact.DateOfBirth),
      dateOfBirthIso: contact.DateOfBirth,
      biologicalSex: biologicalSexFromOracleGender(contact.Gender)
    });
  }
  return dependents;
}

/**
 * Resolves a `StaffProfile` for a given IST staff ID (Oracle `PersonNumber`),
 * implementing the exact runtime flow documented in
 * docs/oracle-fusion-hcm-integration.md: publicWorkers lookup -> assignment
 * for department/job/duty context -> absences for leave context ->
 * hcmContacts/contactRelationships for dependents -> normalize into the
 * stable IST `StaffProfile` shape. Returns undefined if the person number
 * isn't found, matching the "worker does not exist" case a real Oracle
 * adapter would also need to handle.
 */
export function resolveStaffProfile(istStaffId: string): StaffProfile | undefined {
  const index = getIndex();
  const worker = index.publicWorkerByPersonNumber.get(istStaffId.toUpperCase());
  if (!worker) {
    return undefined;
  }

  const assignment = index.assignmentByPersonId.get(worker.PersonId);
  const workerDetail = index.workerByPersonId.get(worker.PersonId);
  const absences = index.absencesByPersonId.get(worker.PersonId) ?? [];
  const hasApprovedAbsence = absences.some((absence) => absence.ApprovalStatusCd === "APPROVED");
  const assignmentStatusType = assignment?.AssignmentStatusType ?? worker.AssignmentStatusType;

  return {
    id: `oracle_person_${worker.PersonId}`,
    istStaffId: worker.PersonNumber,
    department: assignment?.DepartmentName ?? worker.DepartmentName,
    jobTitle: assignment?.JobName ?? worker.JobName,
    dutyStatus: dutyStatusFromOracle(assignmentStatusType, hasApprovedAbsence),
    dateOfBirthIso: workerDetail?.DateOfBirth,
    biologicalSex: workerDetail?.Gender ? biologicalSexFromOracleGender(workerDetail.Gender) : undefined,
    insuranceProvider: "IST Staff Health Plan",
    insuranceEligibilityStatus: "eligible",
    insuranceLastChecked: "2026-07-01T08:00:00.000Z",
    dependents: dependentsForPerson(index, worker.PersonId)
  };
}

/** Resolves either an employee number or a globally unique dependent ID. */
export function resolvePatientIdentifier(patientIdentifier: string):
  | { profile: StaffProfile; dependent?: DependentProfile }
  | undefined {
  const normalized = patientIdentifier.trim();
  if (!normalized) return undefined;

  const staff = resolveStaffProfile(normalized);
  if (staff) return { profile: staff };

  const index = getIndex();
  for (const worker of index.publicWorkerByPersonNumber.values()) {
    const profile = resolveStaffProfile(worker.PersonNumber);
    const dependent = profile?.dependents.find(
      (candidate) => candidate.id.toUpperCase() === normalized.toUpperCase()
    );
    if (profile && dependent) return { profile, dependent };
  }
  return undefined;
}
